package main

import (
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"

	"frc.engineer/internal/signaling"
	"github.com/gorilla/websocket"
)

func main() {
	logger := slog.New(slog.NewTextHandler(os.Stdout, &slog.HandlerOptions{
		Level: slog.LevelInfo,
	}))

	// Railway/Render/Fly set PORT; allow override via SIGNALING_PORT.
	port := os.Getenv("PORT")
	if port == "" {
		port = os.Getenv("SIGNALING_PORT")
	}
	if port == "" {
		port = "9090"
	}

	roomManager := signaling.NewRoomManager(logger)
	defer roomManager.Stop()

	upgrader := websocket.Upgrader{
		ReadBufferSize:  1024,
		WriteBufferSize: 1024,
		CheckOrigin:     func(r *http.Request) bool { return true },
	}

	mux := http.NewServeMux()

	mux.HandleFunc("/ws", func(w http.ResponseWriter, r *http.Request) {
		conn, err := upgrader.Upgrade(w, r, nil)
		if err != nil {
			logger.Error("websocket upgrade failed", "error", err)
			return
		}
		defer conn.Close()

		var currentPeer *signaling.ExportedPeer

		for {
			_, raw, err := conn.ReadMessage()
			if err != nil {
				if currentPeer != nil {
					roomManager.RemoveExportedPeer(currentPeer)
				}
				return
			}
			currentPeer = roomManager.HandleMessageExported(conn, raw, currentPeer)
		}
	})

	mux.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprintf(w, `{"status":"ok"}`)
	})

	server := &http.Server{
		Addr:    ":" + port,
		Handler: mux,
	}

	go func() {
		logger.Info("signaling server started", "addr", server.Addr)
		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			logger.Error("server error", "error", err)
			os.Exit(1)
		}
	}()

	sigChan := make(chan os.Signal, 1)
	signal.Notify(sigChan, syscall.SIGINT, syscall.SIGTERM)
	<-sigChan
	logger.Info("shutting down signaling server")
}
